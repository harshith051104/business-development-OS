"""Section 7: execute_confirmed_action"""
import pathlib
target = pathlib.Path(r"app/services/copilot/engine.py")
s = []
s.append('')
s.append('    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++')
s.append('    # ACTION CONFIRMATION EXECUTION')
s.append('    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++')
s.append('')
s.append('    @classmethod')
s.append('    def execute_confirmed_action(cls, db, user, request):')
s.append('        action_data = PENDING_CONFIRMATIONS.get(request.action_id)')
s.append('        if not action_data:')
s.append('            return CopilotConfirmResponse(')
s.append('                action_id=request.action_id, approved=request.approved,')
s.append('                success=False, message="Action has expired or does not exist."')
s.append('            )')
s.append('')
s.append('        if not request.approved:')
s.append('            del PENDING_CONFIRMATIONS[request.action_id]')
s.append('            return CopilotConfirmResponse(')
s.append('                action_id=request.action_id, approved=False,')
s.append('                success=True, message="Action cancelled by user."')
s.append('            )')
s.append('')
s.append('        payload = request.modified_payload or action_data["payload"]')
s.append('        action_type = action_data["action_type"]')
s.append('        data_refs: List[DataReference] = []')
s.append('')
s.append('        try:')
s.append('            if action_type == "move_connection_stage":')
s.append('                org = db.query(Organization).filter(Organization.id == payload["organization_id"]).first()')
s.append('                if not org:')
s.append('                    return CopilotConfirmResponse(action_id=request.action_id, approved=True, success=False, message="Organization not found.")')
s.append('                old_status = org.status')
s.append('                org.status = payload["target_stage"]')
s.append('                db.commit()')
s.append('                log_audit_event(db, action="COPILOT_STAGE_MOVE", resource_type="ORGANIZATION", resource_id=org.id, user=user, metadata={"old_stage": old_status, "new_stage": org.status})')
s.append('                data_refs.append(DataReference(entity_type="organization", entity_id=org.id, title=org.name, subtitle=f"Moved to {org.status}", url=f"/business-development/organizations/{org.id}"))')
s.append('                del PENDING_CONFIRMATIONS[request.action_id]')
s.append('                return CopilotConfirmResponse(action_id=request.action_id, approved=True, success=True, message=f"Successfully moved **{org.name}** to **{org.status}**.", result_data={"organization_id": org.id, "new_stage": org.status}, data_references=data_refs)')
s.append('')
s.append('            elif action_type == "create_meeting":')
s.append('                scheduled_dt = datetime.fromisoformat(payload["scheduled_at"]) if isinstance(payload["scheduled_at"], str) else payload["scheduled_at"]')
s.append('                org_id = payload.get("organization_id")')
s.append('                if not org_id:')
s.append('                    first_org = db.query(Organization).filter(Organization.is_deleted == False).first()')
s.append('                    org_id = first_org.id if first_org else 1')
s.append('                meeting = Meeting(title=payload["title"], organization_id=org_id, scheduled_at=scheduled_dt, meeting_type=MeetingType.BUSINESS_DISCUSSION.value, status=MeetingStatus.SCHEDULED.value, agenda=payload.get("agenda"), created_by=user.id)')
s.append('                db.add(meeting)')
s.append('                db.commit()')
s.append('                db.refresh(meeting)')
s.append('                log_audit_event(db, action="COPILOT_CREATE_MEETING", resource_type="MEETING", resource_id=meeting.id, user=user, metadata={"title": meeting.title})')
s.append('                data_refs.append(DataReference(entity_type="meeting", entity_id=meeting.id, title=meeting.title, subtitle=meeting.scheduled_at.strftime("%b %d at %I:%M %p"), url=f"/business-development/meetings/{meeting.id}"))')
s.append('                del PENDING_CONFIRMATIONS[request.action_id]')
s.append('                return CopilotConfirmResponse(action_id=request.action_id, approved=True, success=True, message=f"Successfully scheduled meeting **{meeting.title}**.", result_data={"meeting_id": meeting.id}, data_references=data_refs)')
s.append('')
s.append('            elif action_type == "create_followup":')
s.append('                due_dt = datetime.fromisoformat(payload["due_date"]) if isinstance(payload["due_date"], str) else payload["due_date"]')
s.append('                org_id = payload.get("organization_id")')
s.append('                if not org_id:')
s.append('                    first_org = db.query(Organization).filter(Organization.is_deleted == False).first()')
s.append('                    org_id = first_org.id if first_org else 1')
s.append('                fu = FollowUp(title=payload["title"], organization_id=org_id, due_at=due_dt, priority=FollowUpPriority.HIGH.value if payload.get("priority", "").upper() == "HIGH" else FollowUpPriority.MEDIUM.value, status=FollowUpStatus.PENDING.value, description=payload.get("description"), assigned_to=user.name, created_by=user.id)')
s.append('                db.add(fu)')
s.append('                db.commit()')
s.append('                db.refresh(fu)')
s.append('                log_audit_event(db, action="COPILOT_CREATE_FOLLOWUP", resource_type="FOLLOWUP", resource_id=fu.id, user=user, metadata={"title": fu.title})')
s.append('                data_refs.append(DataReference(entity_type="followup", entity_id=fu.id, title=fu.title, subtitle=f"Due: {fu.due_at.strftime(\'%b %d\')}", url=f"/business-development/followups/{fu.id}"))')
s.append('                del PENDING_CONFIRMATIONS[request.action_id]')
s.append('                return CopilotConfirmResponse(action_id=request.action_id, approved=True, success=True, message=f"Successfully created follow-up **{fu.title}**.", result_data={"followup_id": fu.id}, data_references=data_refs)')

with open(target, 'a', encoding='utf-8') as f:
    f.write('\n'.join(s) + '\n')
print(f'S7a done: {target.stat().st_size} bytes')
