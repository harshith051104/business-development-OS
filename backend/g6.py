"""Section 6: _run_llm_agent method"""
import pathlib
target = pathlib.Path(r"app/services/copilot/engine.py")
s = []
s.append('')
s.append('    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++')
s.append('    # LLM AGENT (Tier 2)')
s.append('    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++')
s.append('')
s.append('    @classmethod')
s.append('    def _run_llm_agent(cls, db, user, conversation_id, message, context):')
s.append('        """Run LLM function-calling agent with multi-step tool execution."""')
s.append('        tools_exec: List[ToolExecutionRecord] = []')
s.append('        data_refs: List[DataReference] = []')
s.append('')
s.append('        # Build conversation messages from history')
s.append('        conv = db.query(CopilotConversation).filter(CopilotConversation.id == conversation_id).first()')
s.append('        history_msgs = []')
s.append('        if conv:')
s.append('            past = db.query(CopilotMessage).filter(')
s.append('                CopilotMessage.conversation_id == conversation_id')
s.append('            ).order_by(CopilotMessage.id).all()')
s.append('            for pm in past:')
s.append('                role = "user" if pm.sender == "user" else "assistant"')
s.append('                history_msgs.append({"role": role, "content": pm.content})')
s.append('')
s.append('        # Build context hint')
s.append('        context_hint = ""')
s.append('        if context and context.active_entity_id:')
s.append('            if context.active_entity_type == "organization" or (context.current_page and "/organizations/" in context.current_page):')
s.append('                org = tools.resolve_organization(db, context.active_entity_id)')
s.append('                if org:')
s.append('                    context_hint = f"\\n[Active Organization: {org.name} (ID: {org.id}, Stage: {org.status}, Priority: {org.priority})]"')
s.append('            elif context.active_entity_type == "meeting":')
s.append('                context_hint = f"\\n[Active Meeting ID: {context.active_entity_id}]"')
s.append('            elif context.active_entity_type == "opportunity":')
s.append('                context_hint = f"\\n[Active Opportunity ID: {context.active_entity_id}]"')
s.append('')
s.append('        # Add workload summary for complex queries')
s.append('        workload_hint = ""')
s.append('        try:')
s.append('            dash = tools.get_dashboard_summary(db, user)')
s.append('            workload_hint = (')
s.append('                f"\\n[Current Workload: {dash[\'total_orgs\']} orgs, "')
s.append('                f"{dash[\'active_opportunities_count\']} open deals (Rs.{dash[\'total_pipeline_value\']:,.0f}), "')
s.append('                f"{dash[\'today_meetings\']} meetings today, "')
s.append('                f"{dash[\'overdue_followups\']} overdue follow-ups, "')
s.append('                f"{dash[\'active_partnerships\']} partnerships]"')
s.append('            )')
s.append('        except Exception:')
s.append('            pass')
s.append('')
s.append('        system_content = SYSTEM_PROMPT + context_hint + workload_hint')
s.append('')
s.append('        messages = [{"role": "system", "content": system_content}]')
s.append('        messages.extend(history_msgs)')
s.append('        messages.append({"role": "user", "content": message})')
s.append('')
s.append('        # Create LLM router and run agent loop')
s.append('        router = _get_llm_router()')
s.append('        max_iterations = settings.LLM_MAX_AGENT_ITERATIONS')
s.append('')
s.append('        try:')
s.append('            def tool_executor(name, arguments):')
s.append('                result = execute_tool(db, name, arguments, user)')
s.append('                tools_exec.append(ToolExecutionRecord(')
s.append('                    tool_name=name, arguments=arguments,')
s.append('                    status="success" if "error" not in result else "error",')
s.append('                    summary=f"Executed {name}" if "error" not in result else result.get("error", "Unknown error")')
s.append('                ))')
s.append('                # Track data references for known entity types')
s.append('                if isinstance(result, dict) and "items" in result:')
s.append('                    for item in result["items"][:5]:')
s.append('                        if isinstance(item, dict):')
s.append('                            et = "organization" if "organization_type" in item else ("contact" if "designation" in item else None)')
s.append('                            if et and "id" in item and "name" in item:')
s.append('                                data_refs.append(DataReference(')
s.append('                                    entity_type=et, entity_id=item["id"],')
s.append('                                    title=item["name"],')
s.append('                                    subtitle=item.get("status", item.get("organization_type", "")),')
s.append('                                    url=f"/business-development/{et}s/{item[\'id\']}"')
s.append('                                ))')
s.append('                return result')
s.append('')
s.append('            response = router.chat_with_tools(')
s.append('                messages=messages,')
s.append('                tools=AGENT_TOOL_SCHEMAS,')
s.append('                tool_executor=tool_executor,')
s.append('                max_rounds=max_iterations,')
s.append('            )')
s.append('')
s.append('            reply = response.content or "I was unable to generate a response."')
s.append('            provider_used = response.provider')
s.append('')
s.append('        except AllProvidersExhausted as e:')
s.append('            reply = ("I am unable to reach my AI providers at the moment. "')
s.append('                     "Please try again shortly. (All providers exhausted)")')
s.append('            provider_used = "none"')
s.append('            logger.error("All LLM providers exhausted: %s", e)')
s.append('        except Exception as e:')
s.append('            reply = f"I encountered an error while processing your request. Please try again."')
s.append('            provider_used = "error"')
s.append('            logger.error("LLM agent error: %s", e, exc_info=True)')
s.append('')
s.append('        # Build followups')
s.append('        followups = ["Show dashboard", "Show my priorities", "What meetings do I have?"]')
s.append('')
s.append('        return cls._save_and_return_response(')
s.append('            db, conversation_id, reply,')
s.append('            intent="llm_agent",')
s.append('            tools_executed=tools_exec,')
s.append('            data_references=data_refs,')
s.append('            suggested_followups=followups')
s.append('        )')

with open(target, 'a', encoding='utf-8') as f:
    f.write('\n'.join(s) + '\n')
print(f'S6 done: {target.stat().st_size} bytes')
